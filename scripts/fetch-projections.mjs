/**
 * Bakes ESRI WKT strings into the package at authoring time.
 *
 * Run manually (`npm run projections`) when the table needs new codes. This is
 * deliberately NOT part of the build: the published package must never depend on
 * epsg.io being reachable, and a .prj that silently changes between builds would
 * be worse than one that is missing.
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../src/generated/projections.ts');

/** Codes worth shipping: global basics, the US UTM zones, and NAD83 State Plane. */
const CODES = [
  // Geographic
  4326, 4269, 4267, 4152, 6318, 4258, 4979,
  // Common projected
  3857, 5070, 2163, 3665,
  // UTM, NAD83 (CONUS zones)
  ...range(26910, 26923),
  // UTM, WGS 84 northern hemisphere
  ...range(32610, 32623),
  // UTM, WGS 84 southern hemisphere (a useful subset)
  ...range(32718, 32725),
  // NAD83 State Plane, metres
  ...range(26929, 26998),
];

function range(from, to) {
  return Array.from({ length: to - from + 1 }, (_, i) => from + i);
}

/** Pulls the human-readable name out of the WKT's leading PROJCS/GEOGCS. */
function nameOf(wkt) {
  const match = wkt.match(/^(?:PROJCS|GEOGCS|GEOCCS)\["([^"]+)"/);
  return match ? match[1].replace(/_/g, ' ') : `EPSG:${'unknown'}`;
}

async function fetchWkt(code) {
  const response = await fetch(`https://epsg.io/${code}.esriwkt`);
  if (!response.ok) return null;
  const text = (await response.text()).trim();
  // Unknown codes come back as a 404 and are already filtered above; this guards
  // against a proxy or portal answering with its own 200 page instead.
  if (!/^(PROJCS|GEOGCS|GEOCCS)\[/.test(text)) return null;
  return text;
}

const entries = [];
const missing = [];

// Sequential with a small delay: this is a courtesy scrape of a free service,
// not a hot path.
for (const code of CODES) {
  try {
    const wkt = await fetchWkt(code);
    if (wkt) {
      entries.push({ code, name: nameOf(wkt), wkt });
    } else {
      missing.push(code);
    }
  } catch (error) {
    missing.push(code);
  }
  await new Promise((r) => setTimeout(r, 60));
}

entries.sort((a, b) => a.code - b.code);

const body = entries
  .map(({ code, name, wkt }) => `  // ${name}\n  ${code}: ${JSON.stringify(wkt)},`)
  .join('\n');

const source = `// Generated by scripts/fetch-projections.mjs — do not edit by hand.
// Source: https://epsg.io (ESRI WKT flavour, which is what a .prj file expects).
// Regenerate with \`npm run projections\`.

/**
 * ESRI WKT definitions keyed by EPSG code, ready to be written to a \`.prj\`.
 *
 * Import this table only if you need it — it is a few tens of kilobytes and is
 * kept out of the main entry point on purpose:
 *
 * \`\`\`ts
 * import { registerProjections } from '@crmackey/shapefile-wasm';
 * import { epsgProjections } from '@crmackey/shapefile-wasm/projections';
 *
 * registerProjections(epsgProjections);
 * \`\`\`
 */
export const epsgProjections: Record<number, string> = {
${body}
};

export default epsgProjections;
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, source, 'utf8');

console.log(`wrote ${entries.length} projections to ${OUT}`);
if (missing.length) {
  console.log(`skipped ${missing.length} codes with no ESRI WKT: ${missing.join(', ')}`);
}
